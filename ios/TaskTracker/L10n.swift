enum L10n {
  private static let lock = NSLock()
  private static var current = "en"

  static var code: String {
    lock.lock(); defer { lock.unlock() }
    return current
  }

  static var tag: String { code == "ru" ? "ru_RU" : "en_US" }

  static func set(_ value: String?) {
    let next = value == "ru" ? "ru" : "en"
    lock.lock(); current = next; lock.unlock()
  }

  static func t(_ key: String, _ vars: [String: String] = [:]) -> String {
    let table = code == "ru" ? ru : en
    var text = table[key] ?? en[key] ?? ru[key] ?? key
    for (name, value) in vars {
      text = text.replacingOccurrences(of: "{\(name)}", with: value)
    }
    return text
  }

  static func t(_ key: String, n: Int) -> String { t(key, ["n": String(n)]) }
  static func t(_ key: String, name: String) -> String { t(key, ["name": name]) }

  static func weekdays() -> [String] {
    code == "ru"
      ? ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]
      : ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
  }

  static func repeatCaption(_ rule: String?) -> String {
    switch rule {
    case "1d": return t("repeat1d")
    case "7d": return t("repeat7d")
    case "1m": return t("repeat1m")
    default: return t("noRepeat")
    }
  }

