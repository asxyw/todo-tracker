let current = "en"

export function locale() {
  return current
}

export function localeTag() {
  return current === "ru" ? "ru-RU" : "en-US"
}

export function setLocale(code) {
  current = keepLocale(code)
  return current
}

export function t(key, vars = {}) {
  const table = dict[current] || dict.en
  let text = table[key] ?? dict.en[key] ?? dict.ru[key] ?? key
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function weekdays() {
  return current === "ru"
    ? ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]
    : ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
}

export function keepLocale(value) {
  return value === "ru" ? "ru" : "en"
}

export function repeatCaption(rule) {
  if (rule === "1d") return t("repeat1d")
  if (rule === "7d") return t("repeat7d")
  if (rule === "1m") return t("repeat1m")
  return t("noRepeat")
}

export function repeatShort(rule) {
  if (rule === "1d") return t("day")
  if (rule === "7d") return t("week")
  if (rule === "1m") return t("month")
  return t("repeat")
}
